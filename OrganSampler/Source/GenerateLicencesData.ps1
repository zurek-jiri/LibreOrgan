# Embeds the licence texts into the executable (Source\LicencesData.h) so that the
# "About & licences" dialog needs no external file - the program stays portable.
# Sources: ..\..\ThirdParty\licence-texts\*.txt (GPL-3.0, AGPL-3.0) and the notice
# files in ..\..\ThirdParty\notices. The header is committed to the repository
# (macOS and Linux builds need no PowerShell); Windows regenerates it before each build.
param(
    [string]$Root = (Join-Path $PSScriptRoot '..\..'),
    [string]$Out = (Join-Path $PSScriptRoot 'LicencesData.h')
)

function Escape-Chunks([string]$text)
{
    # MSVC: one string literal <= 16380 bytes, the concatenation <= 65535 bytes.
    $text = $text -replace "`r`n", "`n"
    $lines = $text -split "`n"
    $chunks = New-Object System.Collections.Generic.List[string]
    $current = New-Object System.Text.StringBuilder
    foreach ($line in $lines)
    {
        $escaped = $line.Replace('\', '\\').Replace('"', '\"')
        $piece = '"' + $escaped + '\n"'
        if ($current.Length + $piece.Length > 15000) { $chunks.Add($current.ToString()); $current = New-Object System.Text.StringBuilder }
        [void]$current.AppendLine('    ' + $piece)
    }
    if ($current.Length -gt 0) { $chunks.Add($current.ToString()) }
    return $chunks.ToArray()
}

$items = @(
    @{ Name = 'kLicenceOrganSampler';    File = (Join-Path $Root 'ThirdParty\notices\OrganSampler-notice.txt') },
    @{ Name = 'kLicenceGpl3';            File = (Join-Path $Root 'ThirdParty\licence-texts\GPL-3.0.txt') },
    @{ Name = 'kLicenceJuceNotice';      File = (Join-Path $Root 'ThirdParty\notices\JUCE-notice.txt') },
    @{ Name = 'kLicenceAgpl3';           File = (Join-Path $Root 'ThirdParty\licence-texts\AGPL-3.0.txt') },
    @{ Name = 'kLicenceAsioNotice';      File = (Join-Path $Root 'ThirdParty\notices\ASIO-SDK-notice.txt') },
    @{ Name = 'kLicenceSignalsmithStretch'; File = (Join-Path $Root 'ThirdParty\signalsmith\LICENSE-signalsmith-stretch.txt') },
    @{ Name = 'kLicenceSignalsmithLinear';  File = (Join-Path $Root 'ThirdParty\signalsmith\LICENSE-signalsmith-linear.txt') },
    @{ Name = 'kLicenceLibarchive';         File = (Join-Path $Root 'ThirdParty\notices\libarchive-COPYING.txt') },
    @{ Name = 'kLicenceUnarr';              File = (Join-Path $Root 'ThirdParty\notices\unarr-COPYING.txt') }
)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by Source/GenerateLicencesData.ps1 from ThirdParty/licence-texts and ThirdParty/notices. Do not edit.')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('')
foreach ($item in $items)
{
    if (-not (Test-Path $item.File)) { throw "Missing licence file: $($item.File)" }
    $bytes = [IO.File]::ReadAllBytes($item.File)
    $text = (New-Object System.Text.UTF8Encoding($false)).GetString($bytes).TrimStart([char]0xFEFF)
    # Non-ASCII characters become UTF-8 byte escapes so the source compiles under any charset.
    $ascii = New-Object System.Text.StringBuilder
    foreach ($ch in $text.ToCharArray())
    {
        $code = [int]$ch
        if ($code -lt 128) { [void]$ascii.Append($ch) }
        else { foreach ($b in [System.Text.Encoding]::UTF8.GetBytes([string]$ch)) { [void]$ascii.Append(('\x{0:X2}' -f $b)) }; [void]$ascii.Append('""') }
    }
    $chunks = @(Escape-Chunks $ascii.ToString())
    $parts = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $chunks.Count; $i++)
    {
        $partName = $item.Name + '_part' + $i
        $parts.Add($partName)
        [void]$sb.AppendLine("static const char* const $partName =")
        [void]$sb.Append($chunks[$i])
        [void]$sb.AppendLine('    ;')
    }
    [void]$sb.AppendLine("static const char* const $($item.Name)Parts[] = { " + (($parts | ForEach-Object { $_ }) -join ', ') + " };")
    [void]$sb.AppendLine("static const int $($item.Name)PartCount = $($parts.Count);")
    [void]$sb.AppendLine('')
}
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
"LicencesData.h written: $([IO.FileInfo]::new($Out).Length) bytes"
