#!/usr/bin/env python3
"""Embeds USER_MANUAL.md into Source/ManualData.h - the same output as
Source/GenerateManualData.ps1 (the Windows pre-build step), for macOS and
Linux where there is no PowerShell. Run from anywhere:
    python3 LibreOrgan/Tools/generate_manual_data.py
"""
import os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
manual = os.path.join(root, 'USER_MANUAL.md')
out = os.path.join(root, 'Source', 'ManualData.h')
text = open(manual, encoding='utf-8').read().replace('\r\n', '\n')
lines = text.split('\n')
chunks, current, count = [], [], 0
for line in lines:
    escaped = []
    for ch in line:
        code = ord(ch)
        if ch == '\\': escaped.append('\\\\')
        elif ch == '"': escaped.append('\\"')
        elif 32 <= code < 127: escaped.append(ch)
        else:
            escaped.append(''.join('\\x%02X' % b for b in ch.encode('utf-8')) + '""')
    current.append('    "' + ''.join(escaped) + '\\n"\n')
    count += 1
    if count >= 200:
        chunks.append(''.join(current)); current, count = [], 0
if current: chunks.append(''.join(current))
sb = ['// Generated by Source/GenerateManualData.ps1 from USER_MANUAL.md. Do not edit.\n', '#pragma once\n', '\n']
for i, chunk in enumerate(chunks):
    sb.append('static const char* const kManualText_part%d =\n' % i)
    sb.append(chunk)
    sb.append('    ;\n')
sb.append('static const char* const kManualTextParts[] = { ' + ', '.join('kManualText_part%d' % i for i in range(len(chunks))) + ' };\n')
sb.append('static const int kManualTextPartCount = %d;\n' % len(chunks))
content = ''.join(sb)
if os.path.exists(out) and open(out, encoding='utf-8').read() == content:
    print('ManualData.h unchanged'); sys.exit(0)
open(out, 'w', encoding='utf-8', newline='').write(content)
print('ManualData.h written: %d bytes, %d part(s)' % (len(content.encode('utf-8')), len(chunks)))
