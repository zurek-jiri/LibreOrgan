# Embeds USER_MANUAL.md into the executable (Source\ManualData.h) so that the
# "?" buttons of the Configuration Editor can open the manual at a section
# without any file beside the exe (the program stays one portable file).
# Called by GenerateTemperamentsData.ps1 (the pre-build step), like the licences.
param(
    [string]$Manual = (Join-Path (Split-Path $PSScriptRoot -Parent) 'USER_MANUAL.md'),
    [string]$Out = (Join-Path $PSScriptRoot 'ManualData.h')
)

function Escape-Chunks([string]$text)
{
    # MSVC: one string literal <= 16380 bytes, the concatenation <= 65535 bytes;
    # non-ASCII characters as UTF-8 hex escapes (the file stays ASCII).
    $text = $text -replace "`r`n", "`n"
    $lines = $text -split "`n"
    $chunks = New-Object System.Collections.Generic.List[string]
    $current = New-Object System.Text.StringBuilder
    $count = 0
    foreach ($line in $lines)
    {
        $escaped = New-Object System.Text.StringBuilder
        foreach ($ch in $line.ToCharArray())
        {
            $code = [int]$ch
            if ($ch -eq '\') { [void]$escaped.Append('\\') }
            elseif ($ch -eq '"') { [void]$escaped.Append('\"') }
            elseif ($code -ge 32 -and $code -lt 127) { [void]$escaped.Append($ch) }
            else
            {
                foreach ($b in [System.Text.Encoding]::UTF8.GetBytes([string]$ch)) { [void]$escaped.Append(('\x{0:X2}' -f $b)) }
                [void]$escaped.Append('""')
            }
        }
        $piece = '"' + $escaped.ToString() + '\n"'
        [void]$current.AppendLine('    ' + $piece)
        $count++
        if ($count -ge 200) { $chunks.Add($current.ToString()); $current = New-Object System.Text.StringBuilder; $count = 0 }   # 200 lines per part: well under MSVC's 65535 bytes
    }
    if ($current.Length -gt 0) { $chunks.Add($current.ToString()) }
    return ,$chunks.ToArray()
}

if (-not (Test-Path $Manual)) { "manual not found: $Manual"; exit 1 }
$text = [IO.File]::ReadAllText($Manual, [System.Text.Encoding]::UTF8)
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by Source/GenerateManualData.ps1 from USER_MANUAL.md. Do not edit.')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('')
$chunks = Escape-Chunks $text   # the function returns the array as one object (", $array"), so one chunk stays an array too
for ($i = 0; $i -lt $chunks.Count; $i++)
{
    [void]$sb.AppendLine("static const char* const kManualText_part$i =")
    [void]$sb.Append($chunks[$i])
    [void]$sb.AppendLine('    ;')
}
$names = @(); for ($i = 0; $i -lt $chunks.Count; $i++) { $names += "kManualText_part$i" }
[void]$sb.AppendLine('static const char* const kManualTextParts[] = { ' + ($names -join ', ') + ' };')
[void]$sb.AppendLine("static const int kManualTextPartCount = $($chunks.Count);")
$content = $sb.ToString()
if ((Test-Path $Out) -and ([IO.File]::ReadAllText($Out) -eq $content)) { "ManualData.h unchanged"; exit 0 }
[IO.File]::WriteAllText($Out, $content, (New-Object System.Text.UTF8Encoding($false)))
"ManualData.h written: $([IO.FileInfo]::new($Out).Length) bytes, $($chunks.Count) part(s)"
